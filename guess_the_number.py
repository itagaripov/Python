import random
import time

def guess_the_number():
    """
    Основная функция игры "Угадай число".
    """
    # Загадываем случайное число от 1 до 100
    secret_number = random.randint(1, 100)
    
    # Ограничиваем количество попыток
    max_attempts = 7
    
    print("Добро пожаловать в игру 'Угадай число'!")
    print(f"Я загадал число от 1 до 100. У тебя есть {max_attempts} попыток, чтобы угадать его.")
    
    # Запускаем цикл игры
    for attempt in range(1, max_attempts + 1):
        try:
            # Запрашиваем у пользователя предположение
            guess = int(input(f"Попытка №{attempt}: Введите ваше предположение: "))
            
            # Проверяем предположение
            if guess < secret_number:
                print("Слишком маленькое число. Попробуй еще раз.")
            elif guess > secret_number:
                print("Слишком большое число. Попробуй еще раз.")
            else:
                # Если угадал
                print(f"Поздравляю! Ты угадал число {secret_number} за {attempt} попыток!")
                time.sleep(10)
                return  # Завершаем игру через 10 сек
        
        except ValueError:
            # Обработка ошибки, если пользователь ввел не число
            print("Неверный ввод. Пожалуйста, введите целое число.")
    
    # Если попытки закончились
    print(f"\nК сожалению, твои попытки закончились. Загаданное число было {secret_number}.")

# Запускаем игру
if __name__ == "__main__":
    guess_the_number()