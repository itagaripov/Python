import math
import time

def calculate_factorial(n):
    """
    Вычисляет факториал числа n.
    Использует библиотеку math для эффективного вычисления.
    """
    if n < 0:
        raise ValueError("Факториал определен только для неотрицательных чисел.")
    return math.factorial(n)

def main():
    """
    Основная функция программы.
    Запрашивает число, вычисляет факториал и выводит результат.
    """
    while True:
        user_input = input("Пожалуйста, введите положительное целое число: ")
        try:
            # Преобразование ввода в целое число
            number = int(user_input)

            # Проверка, является ли число положительным
            if number < 0:
                print("Ошибка: Вы ввели отрицательное число. Пожалуйста, введите положительное.")
            else:
                # Вычисление и вывод факториала
                factorial_result = calculate_factorial(number)
                print(f"Факториал числа {number} равен {factorial_result}")
                time.sleep(10)
                break  # Выход из цикла после успешного выполнения через 10 сек

        except ValueError:
            # Обработка ошибки, если ввод не является числом
            print("Ошибка: Неверный ввод. Пожалуйста, введите целое число.")

if __name__ == "__main__":
    main()
    
    